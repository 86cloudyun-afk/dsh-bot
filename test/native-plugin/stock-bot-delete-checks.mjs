import assert from 'node:assert/strict';
import {waitFor} from './stock-gui-runtime.mjs';

export async function runBotDeleteChecks(gui) {
  await gui.workbench('Bots');
  const editor=gui.card('创建具名 Bot');await editor.getByLabel('名称',{exact:true}).fill('删除验证Bot');
  await editor.getByRole('button',{name:'创建 Bot',exact:true}).click();
  const bot=(await gui.until(s=>s.bots.some(row=>row.name==='删除验证Bot'),'delete fixture Bot')).bots.find(row=>row.name==='删除验证Bot');
  await gui.workbench('记忆');await gui.page.getByLabel('所属 Bot',{exact:true}).selectOption(bot.botId);
  await gui.page.getByLabel('内容',{exact:true}).fill('删除与恢复应保留这条记忆');
  await gui.page.getByRole('button',{name:'保存到所选 Bot',exact:true}).click();
  const memory=(await gui.until(s=>s.memories.some(row=>row.botId===bot.botId),'delete fixture memory')).memories.find(row=>row.botId===bot.botId);
  await gui.workbench('Bots');await gui.card(bot.name).getByRole('button',{name:'开始聊天',exact:true}).click();
  const contact=(await gui.until(s=>s.sessions.some(row=>row.botId===bot.botId),'delete fixture contact')).sessions.find(row=>row.botId===bot.botId);
  await gui.page.getByRole('heading',{name:'Bot 工作台',exact:true}).waitFor({state:'hidden'});
  await gui.page.locator('[data-slot="conversation.input.dock"]').getByRole('button',{name:`正在与${bot.name}聊天`,exact:true}).waitFor();
  await gui.workbench('Bots');
  await gui.card(bot.name).getByRole('button',{name:'编辑',exact:true}).click();
  await gui.card('编辑 Bot').waitFor();
  const before=(await gui.snapshot()).revision;
  await gui.card(bot.name).getByRole('button',{name:'删除',exact:true}).click({timeout:5000});
  const dialog=gui.page.getByRole('dialog',{name:'删除 Bot',exact:true});await dialog.waitFor();
  assert.equal(await dialog.getByRole('button',{name:'取消',exact:true}).evaluate(node=>node===document.activeElement),true,'Delete confirmation must initially focus safe Cancel');
  await gui.page.keyboard.press('Shift+Tab');
  assert.equal(await dialog.evaluate(node=>node.contains(document.activeElement)),true,'Keyboard focus must stay inside confirmation');
  await gui.page.keyboard.press('Escape');await dialog.waitFor({state:'hidden'});
  assert.equal(await gui.card(bot.name).getByRole('button',{name:'删除',exact:true}).evaluate(node=>node===document.activeElement),true);
  assert.equal((await gui.snapshot()).revision,before);
  gui.check('deleteDialogContainsKeyboardFocusAndEscapeCancels',true);
  await gui.card(bot.name).getByRole('button',{name:'删除',exact:true}).click();await dialog.waitFor();
  assert.equal((await gui.snapshot()).revision,before);
  await dialog.getByRole('button',{name:'取消',exact:true}).click();await dialog.waitFor({state:'hidden'});
  assert.equal((await gui.snapshot()).bots.find(row=>row.botId===bot.botId).deletedAt,undefined);
  gui.check('botDeletionRequiresExplicitConfirmation',true);
  await gui.card(bot.name).getByRole('button',{name:'删除',exact:true}).click();await dialog.waitFor();
  const service=gui.app.ctx.dshBot,actor=service.policy.fromPeer(gui.app.ctx.connection.operator);
  await service.dispatch(actor,{operationId:crypto.randomUUID(),action:'bot.update',input:{botId:bot.botId,expectedVersion:(await gui.snapshot()).bots.find(row=>row.botId===bot.botId).revision,role:'另一个页面保存的职责'}});
  await dialog.getByRole('status').filter({hasText:'其他页面修改'}).waitFor();
  assert.equal(await dialog.getByRole('button',{name:'确认删除',exact:true}).isDisabled(),true);
  await dialog.getByRole('button',{name:'取消',exact:true}).click();await dialog.waitFor({state:'hidden'});
  assert.equal((await gui.snapshot()).bots.find(row=>row.botId===bot.botId).deletedAt,undefined);
  gui.check('staleDeleteConfirmationCannotOverrideAnotherPage',true);
  const callsBefore=gui.report.requests.length;
  await gui.card(bot.name).getByRole('button',{name:'删除',exact:true}).click();
  await dialog.getByRole('button',{name:'确认删除',exact:true}).click();await dialog.waitFor({state:'hidden'});
  const removed=await gui.until(s=>!!s.bots.find(row=>row.botId===bot.botId)?.deletedAt,'deleted Bot tombstone');
  assert.equal(removed.bots.find(row=>row.botId===bot.botId).lifecycle,'archived');
  assert.deepEqual(removed.memories.find(row=>row.memoryId===memory.memoryId),memory);
  assert.equal(removed.sessions.find(row=>row.sessionId===contact.sessionId).botId,bot.botId);
  assert.equal(gui.report.requests.length,callsBefore);
  assert.equal(await gui.card(bot.name).count(),0);
  await gui.card('创建具名 Bot').waitFor();
  assert.equal(await gui.card('编辑 Bot').count(),0);
  gui.check('deletingEditedBotClosesItsStaleEditor',true);
  gui.check('deletedBotLeavesMainListAndKeepsHistoryAndMemory',true);
  await gui.page.getByRole('button',{name:'新建 Bot 会话',exact:true}).last().click();
  const chooser=gui.page.getByRole('dialog',{name:'新建 Bot 会话'});await chooser.waitFor();
  assert.equal(await chooser.locator(`option[value="${bot.botId}"]`).count(),0);
  await chooser.getByRole('button',{name:'关闭',exact:true}).click();
  gui.check('deletedBotCannotBeChosenForNewChat',true);
  await gui.workbench('会话管理');
  await gui.page.locator('article.card').filter({has:gui.page.locator('small').filter({hasText:contact.sessionId})})
    .getByRole('button',{name:'查看原生会话',exact:true}).click();
  await gui.page.locator('[data-slot="conversation.input.dock"]').getByRole('button',{name:`${bot.name} · 已删除 Bot 的历史会话`,exact:true}).waitFor();
  gui.check('deletedOriginalChatShowsHistoricalBotIdentity',true);
  await gui.workbench('Bots');
  const deleted=gui.page.locator('details').filter({has:gui.page.locator('summary').filter({hasText:'已删除的 Bot'})});
  await deleted.locator('summary').click();
  await deleted.getByRole('button',{name:'恢复',exact:true}).click();
  const restored=await gui.until(s=>!s.bots.find(row=>row.botId===bot.botId)?.deletedAt,'restore same Bot');
  assert.equal(restored.bots.find(row=>row.botId===bot.botId).lifecycle,'paused');
  assert.equal(restored.memories.find(row=>row.memoryId===memory.memoryId).text,memory.text);
  assert.equal(restored.sessions.find(row=>row.sessionId===contact.sessionId).botId,bot.botId);
  await gui.card(bot.name).waitFor();
  assert.equal(await gui.card(bot.name).getByRole('button',{name:'开始聊天',exact:true}).isDisabled(),true);
  gui.check('restoreKeepsBotIdentityPausedUntilExplicitActivation',true);
  await gui.expand(gui.card(bot.name),'状态管理');
  await gui.card(bot.name).getByRole('button',{name:'启用',exact:true}).click();
  await gui.until(s=>s.bots.find(row=>row.botId===bot.botId)?.lifecycle==='active','activate restored Bot');
  await gui.workbench('会话管理');
  await gui.page.locator('article.card').filter({has:gui.page.locator('small').filter({hasText:contact.sessionId})})
    .getByRole('button',{name:'查看原生会话',exact:true}).click();
  await gui.page.locator('[data-slot="conversation.input.dock"]').getByRole('button',{name:`正在与${bot.name}聊天`,exact:true}).waitFor();
  const input=gui.page.locator('[data-composer-input="true"][contenteditable="true"]');await input.fill('恢复后继续聊天');await input.press('Enter');
  await waitFor(()=>gui.report.requests.some(row=>row.sessionId===contact.sessionId&&row.finish==='stop'),'restored original native chat');
  gui.check('restoredBotContinuesItsOriginalNativeChat',true);
}
